/**
 * build-client.mjs — 把浏览器半边打成 DSH 能加载的产物。
 *
 * 为什么需要构建：DSH 前端用 `window.__ModuleLoader__.load({ id, factory })` 这个
 * **自定义模块壳**加载第三方插件，工厂函数收到一个 `require`（能取 `react` /
 * `react-dom`），并返回 `module.exports`。这不是标准 ESM 环境，所以 `lib/client.js`
 * 这类源码不能直接丢进去 —— 需要包一层壳，并把共享的 `settings-schema.js` 内联
 * （前端不吃相对 import，内联是唯一能让两侧共用同一份公式/白名单而不复制粘贴的办法）。
 *
 * 内联方式：把 `settings-schema.js` 去掉 `export` 关键字后注入工厂作用域开头，
 * 于是 `client.js` 正文里那些名字（DEFAULTS / LIMITS / sanitizeSettings …）
 * 直接可见，**没有第二份副本**（两侧共用同一文件 = 不会漂）。
 *
 * 用法：node scripts/build-client.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const PKG = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const PLUGIN_ID = PKG.name;

/** 读一份源码，去掉 ESM 的 import/export 语法（内联用）。 */
function stripModuleSyntax(source, file) {
  let out = source;
  // 多行 import（`import {\n a,\n b,\n} from '…';`）必须先处理。
  out = out.replace(/^[ \t]*import\s+[\s\S]*?from\s*['"][^'"]*['"]\s*;?[ \t]*$/gm, '');
  out = out.replace(/^[ \t]*import\s*['"][^'"]*['"]\s*;?[ \t]*$/gm, '');
  out = out.replace(/^[ \t]*export\s+default\s+/gm, 'const __default__ = ');
  out = out.replace(/^([ \t]*)export\s+(const|let|var|function|class)\s/gm, '$1$2 ');
  out = out.replace(/^[ \t]*export\s*\{[^}]*\}\s*;?[ \t]*$/gm, '');
  if (/^[ \t]*export\b/m.test(out)) {
    throw new Error(`build-client: unhandled export syntax remains in ${file}`);
  }
  if (/^[ \t]*import\b/m.test(out)) {
    throw new Error(`build-client: unhandled import syntax remains in ${file}`);
  }
  return out;
}

const schemaSource = stripModuleSyntax(
  readFileSync(join(root, 'lib', 'settings-schema.js'), 'utf8'),
  'lib/settings-schema.js',
);
const clientSource = stripModuleSyntax(
  readFileSync(join(root, 'lib', 'client.js'), 'utf8'),
  'lib/client.js',
);

const banner = `/**
 * dsh-plugin-retry-backoff — client bundle (GENERATED by scripts/build-client.mjs; do not edit).
 *
 * 设置面板（网页端与桌面端共用同一份产物）。源码见 lib/client.js 与
 * lib/settings-schema.js —— 后者被内联进本文件，因此两侧永远同一份白名单与公式。
 */`;

const bundle = `${banner}
window.__ModuleLoader__.load({
	id: ${JSON.stringify(PLUGIN_ID)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

		// 前端模块壳提供的 require：插件自己从它取 react（不是 ctx.get('react')，
		// 前端不把 react 作为服务暴露）。见 lib/client.js 的 apply()。
		const __RB_REQUIRE__ = require;

// ── inlined: lib/settings-schema.js ─────────────────────────────────────────
${schemaSource}
// ── inlined: lib/client.js ──────────────────────────────────────────────────
${clientSource}

		exports.apply = apply;
		exports.inject = inject;
		return module.exports;
	},
});
`;

const outFile = join(root, 'lib', 'client.bundle.js');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, bundle, 'utf8');
console.log(`build-client: wrote ${outFile} (${Buffer.byteLength(bundle)} bytes)`);